import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { tokensToCss } from "../../src/engine/tokens/to-css.ts";
import { parseDtcg } from "../../src/engine/tokens/dtcg.ts";
import type { TokensToCss } from "../../src/contracts/engine.ts";

const _t: TokensToCss = tokensToCss;
void _t;

describe("tokensToCss", () => {
  it("reproduces the fixture tokens.css exactly", () => {
    const set = parseDtcg(readFileSync("tests/fixtures/northfield/tokens.json", "utf8"), "tokens.json");
    expect(tokensToCss(set)).toBe(readFileSync("tests/fixtures/northfield/tokens.css", "utf8"));
  });
  it("writes aliases as var() and skips empty media blocks", () => {
    const css = tokensToCss({ file: null, tokens: [
      { name: "b", type: "color", value: "#000000", alias: "a", byBreakpoint: {} },
      { name: "a", type: "color", value: "#000000", alias: null, byBreakpoint: {} },
    ] });
    expect(css).toBe("/* Generated by Mason from tokens.json. Do not edit. */\n:root {\n  --a: #000000;\n  --b: var(--a);\n}\n");
  });
});
