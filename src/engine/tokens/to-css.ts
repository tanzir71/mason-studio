import type { TokenSet } from "../../contracts/model.ts";
import { cssVarName } from "./dtcg.ts";

/** See TokensToCss in src/contracts/engine.ts. */
export function tokensToCss(set: TokenSet): string {
  const tokens = [...set.tokens].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const lines = ["/* Generated by Mason from tokens.json. Do not edit. */", ":root {"];
  for (const t of tokens) lines.push(`  ${cssVarName(t.name)}: ${t.alias ? `var(${cssVarName(t.alias)})` : t.value};`);
  lines.push("}");
  for (const [bp, max] of [["tablet", 768], ["mobile", 375]] as const) {
    const list = tokens.filter((t) => t.byBreakpoint[bp] !== undefined);
    if (list.length === 0) continue;
    lines.push(`@media (max-width: ${max}px) {`, "  :root {");
    for (const t of list) lines.push(`    ${cssVarName(t.name)}: ${t.byBreakpoint[bp]};`);
    lines.push("  }", "}");
  }
  return lines.join("\n") + "\n";
}
